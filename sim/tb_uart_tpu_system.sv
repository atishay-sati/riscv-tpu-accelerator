
`timescale 1ns / 1ps

module tb_uart_tpu_system;

    // ============================================================
    // TEST CONFIGURATION
    // ============================================================

    // The FPGA clock is still 100 MHz.
    // We use 1 Mbps in simulation to reduce UART simulation time.
    // The actual hardware configuration will use 115200 baud.
    localparam integer CLOCK_FREQ_HZ = 100_000_000;
    localparam integer BAUD_RATE     = 1_000_000;

    // The input image contains 28 x 28 = 784 pixels.
    localparam integer NUM_PIXELS = 784;

    // The model produces 32 output scores, one per class.
    localparam integer NUM_CLASSES = 32;

    // UART packet header.
    localparam logic [7:0] PACKET_HEADER = 8'hAA;

    // Input pixels used by the previously verified TPU test.
    localparam INPUT_FILE =
        "mem_files/dense_layer_test/input_pixels.mem";

    // Expected output scores generated by the software model.
    localparam EXPECTED_OUTPUTS_FILE =
        "mem_files/output_layer_test/expected_outputs.mem";


    // ============================================================
    // CLOCK AND RESET
    // ============================================================

    logic clk;
    logic reset;

    // Generate a 100 MHz clock.
    // One clock period = 10 ns.
    initial begin
        clk = 1'b0;
        forever #5 clk = ~clk;
    end


    // ============================================================
    // COMPUTER-TO-FPGA UART CONNECTION
    // ============================================================

    // The computer's simulated UART transmitter sends bytes
    // into the FPGA's UART receive pin.
    logic computer_uart_tx;

    // The computer-side UART transmitter signals.
    logic [7:0] computer_tx_data;
    logic       computer_tx_start;
    logic       computer_tx_busy;
    logic       computer_tx_done;


    // ============================================================
    // FPGA-TO-COMPUTER UART CONNECTION
    // ============================================================

    // The FPGA sends its predicted class through this pin.
    logic fpga_uart_tx;

    // The computer's simulated UART receiver captures the result.
    logic [7:0] computer_rx_data;
    logic       computer_rx_valid;
    logic       computer_rx_framing_error;


    // ============================================================
    // FPGA STATUS SIGNALS
    // ============================================================

    logic       controller_busy;
    logic       tpu_busy;
    logic       packet_done;
    logic       packet_error;
    logic [4:0] predicted_class;


    // ============================================================
    // TPU INFERENCE TIMING
    // ============================================================

    // These variables measure how long the actual TPU remains busy.
    //
    // The measurement starts when tpu_busy becomes 1.
    // It ends when tpu_busy returns to 0.
    //
    // This excludes the UART image transfer and result transmission.

    logic tpu_busy_previous;

    // Simulation timestamps for the beginning and end of inference.
    time tpu_inference_start_time;
    time tpu_inference_end_time;

    // Total elapsed simulation time in nanoseconds.
    time tpu_inference_elapsed_ns;

    // Number of 100 MHz clock cycles spent in the busy interval.
    integer tpu_inference_cycles;

    // Inference duration converted into milliseconds.
    real tpu_inference_time_ms;

    // Indicates whether a complete timing measurement was captured.
    logic tpu_inference_measured;


    // ============================================================
    // TEST DATA
    // ============================================================

    // These arrays hold the input image and expected TPU outputs.
    logic [7:0] input_pixels [0:NUM_PIXELS-1];

    // Expected scores are stored as 32-bit hexadecimal values.
    // Their lowest 8 bits represent the quantized INT8 score.
    logic signed [31:0] expected_outputs [0:NUM_CLASSES-1];

    // Expected class calculated from the reference output scores.
    integer expected_class_index;

    // Variables used to find the largest reference score.
    integer i;
    logic signed [31:0] max_score;

    // Signed interpretation of one expected INT8 output score.
    logic signed [7:0] expected_score_signed;

    // Counts how many of the 32 output scores differ.
    integer score_errors;


    // ============================================================
    // TEST COUNTERS
    // ============================================================

    integer received_result_count;
    integer packet_done_count;
    integer packet_error_count;
    integer framing_error_count;
    integer input_errors;


    // ============================================================
    // COMPUTER-SIDE UART TRANSMITTER
    // ============================================================

    // This simulates the computer sending bytes to the FPGA.
    // Its serial output is connected directly to the FPGA UART RX.
    uart_tx #(
        .CLOCK_FREQ_HZ(CLOCK_FREQ_HZ),
        .BAUD_RATE(BAUD_RATE)
    ) computer_uart_transmitter (
        .clk(clk),
        .reset(reset),

        .data_in(computer_tx_data),
        .tx_start(computer_tx_start),

        .tx(computer_uart_tx),
        .tx_busy(computer_tx_busy),
        .tx_done(computer_tx_done)
    );


    // ============================================================
    // FPGA UART-TO-TPU SYSTEM
    // ============================================================

    // This is the actual design being tested.
    //
    // It contains:
    //   1. FPGA UART receiver
    //   2. UART-to-TPU controller
    //   3. Actual TPU
    //   4. FPGA UART transmitter
    //
    // The model memory files are loaded by the actual TPU.
    //
    // LOAD_INPUT_FROM_FILE is disabled inside the wrapper.
    // The TPU must receive its pixels through the UART interface.
    uart_tpu_system #(
        .CLOCK_FREQ_HZ(CLOCK_FREQ_HZ),
        .BAUD_RATE(BAUD_RATE),

        .HIDDEN_WEIGHTS_FILE(
            "mem_files/dense_layer_test/hidden_weights.mem"
        ),

        .HIDDEN_BIASES_FILE(
            "mem_files/dense_layer_test/hidden_biases.mem"
        ),

        .HIDDEN_MULTIPLIERS_FILE(
            "mem_files/dense_layer_test/hidden_multipliers.mem"
        ),

        .HIDDEN_SHIFTS_FILE(
            "mem_files/dense_layer_test/hidden_shifts.mem"
        ),

        .INPUT_PIXELS_FILE(
            INPUT_FILE
        ),

        .OUTPUT_WEIGHTS_FILE(
            "mem_files/output_layer_test/output_weights.mem"
        ),

        .OUTPUT_BIASES_FILE(
            "mem_files/output_layer_test/output_biases.mem"
        ),

        .OUTPUT_MULTIPLIERS_FILE(
            "mem_files/output_layer_test/output_multipliers.mem"
        ),

        .OUTPUT_SHIFTS_FILE(
            "mem_files/output_layer_test/output_shifts.mem"
        )
    ) dut (
        .clk(clk),
        .reset(reset),

        .uart_rx_pin(computer_uart_tx),
        .uart_tx_pin(fpga_uart_tx),

        .controller_busy(controller_busy),
        .tpu_busy(tpu_busy),

        .packet_done(packet_done),
        .packet_error(packet_error),

        .predicted_class(predicted_class)
    );


    // ============================================================
    // COMPUTER-SIDE UART RECEIVER
    // ============================================================

    // This simulates the computer receiving the FPGA's prediction.
    // Its serial input is connected to the FPGA UART TX pin.
    uart_rx #(
        .CLOCK_FREQ_HZ(CLOCK_FREQ_HZ),
        .BAUD_RATE(BAUD_RATE)
    ) computer_uart_receiver (
        .clk(clk),
        .reset(reset),

        .rx(fpga_uart_tx),

        .data_out(computer_rx_data),
        .data_valid(computer_rx_valid),
        .framing_error(computer_rx_framing_error)
    );


    // ============================================================
    // MONITOR TPU INFERENCE LATENCY
    // ============================================================

    // This monitor measures only the time the TPU spends busy.
    //
    // It does not include:
    //   - Receiving the 784 image pixels over UART.
    //   - Sending the predicted class back over UART.
    //   - Computer-side Python processing.
    //
    // The clock period is 10 ns, so:
    //
    //   Clock cycles = elapsed nanoseconds / 10
    //
    //   Inference milliseconds = elapsed nanoseconds / 1,000,000

    always @(posedge clk) begin

        if (reset) begin

            // Clear the timing measurement during reset.
            tpu_busy_previous       = 1'b0;
            tpu_inference_start_time = 0;
            tpu_inference_end_time   = 0;
            tpu_inference_elapsed_ns = 0;
            tpu_inference_cycles     = 0;
            tpu_inference_time_ms    = 0.0;
            tpu_inference_measured   = 1'b0;

        end
        else begin

            // Detect the rising edge of tpu_busy.
            // This marks the beginning of TPU inference.
            if (tpu_busy && !tpu_busy_previous) begin

                tpu_inference_start_time = $time;

                $display("");
                $display("TPU INFERENCE STARTED at %0t ns", $time);

            end


            // Detect the falling edge of tpu_busy.
            // This marks the end of TPU inference.
            if (!tpu_busy && tpu_busy_previous) begin

                tpu_inference_end_time = $time;

                // Calculate elapsed simulation time.
                tpu_inference_elapsed_ns =
                    tpu_inference_end_time - tpu_inference_start_time;

                // Convert elapsed time into 100 MHz clock cycles.
                tpu_inference_cycles =
                    tpu_inference_elapsed_ns / 10;

                // Convert nanoseconds into milliseconds.
                tpu_inference_time_ms =
                    tpu_inference_elapsed_ns / 1000000.0;

                tpu_inference_measured = 1'b1;

                $display("");
                $display("================================================");
                $display("           TPU INFERENCE TIMING");
                $display("================================================");

                $display(
                    "Start time:       %0t ns",
                    tpu_inference_start_time
                );

                $display(
                    "End time:         %0t ns",
                    tpu_inference_end_time
                );

                $display(
                    "Elapsed time:     %0t ns",
                    tpu_inference_elapsed_ns
                );

                $display(
                    "Clock cycles:     %0d",
                    tpu_inference_cycles
                );

                $display(
                    "Inference time:   %0.6f ms",
                    tpu_inference_time_ms
                );

                $display("================================================");
                $display("");

            end


            // Save the current busy state for edge detection
            // during the next clock cycle.
            tpu_busy_previous = tpu_busy;

        end

    end


    // ============================================================
    // MONITOR RECEIVED UART DATA AND STATUS
    // ============================================================

    // Count every result byte received by the computer.
    always @(posedge clk) begin

        if (reset) begin
            received_result_count <= 0;
            packet_done_count     <= 0;
            packet_error_count    <= 0;
            framing_error_count   <= 0;
        end
        else begin

            if (computer_rx_valid) begin
                received_result_count <= received_result_count + 1;
            end

            if (packet_done) begin
                packet_done_count <= packet_done_count + 1;
            end

            if (packet_error) begin
                packet_error_count <= packet_error_count + 1;
            end

            if (computer_rx_framing_error) begin
                framing_error_count <= framing_error_count + 1;
            end

        end
    end


    // ============================================================
    // DEBUG: MONITOR PACKET COMPLETION
    // ============================================================

    // This monitor is outside the initial block.
    // It prints whenever the controller asserts packet_done.
    always @(posedge clk) begin

        if (!reset && packet_done) begin
            $display(
                "DEBUG: packet_done asserted at time %0t",
                $time
            );
        end

    end


    // ============================================================
    // TASK: SEND ONE UART BYTE FROM THE COMPUTER
    // ============================================================

    // This task sends one byte using the simulated computer UART.
    //
    // It waits until the transmitter finishes before returning.
    // This prevents the next byte from being sent too early.
    task automatic send_uart_byte(input logic [7:0] data);
        begin

            // Set up the byte and request transmission.
            @(negedge clk);
            computer_tx_data  = data;
            computer_tx_start = 1'b1;

            // The transmitter samples tx_start on a rising edge.
            @(negedge clk);
            computer_tx_start = 1'b0;

            // Wait until transmission actually begins.
            wait (computer_tx_busy == 1'b1);

            // Wait until the entire UART frame has been transmitted.
            wait (computer_tx_busy == 1'b0);

            // Allow a couple of clock cycles before sending again.
            repeat (2) @(posedge clk);

        end
    endtask


    // ============================================================
    // MAIN TEST
    // ============================================================

    initial begin

        $display("");
        $display("================================================");
        $display("       COMPLETE UART-TO-TPU SYSTEM TEST");
        $display("================================================");
        $display("");


        // --------------------------------------------------------
        // STEP 1: INITIALIZE SIGNALS
        // --------------------------------------------------------

        reset             = 1'b1;

        computer_tx_data  = 8'h00;
        computer_tx_start = 1'b0;

        expected_class_index = 0;
        max_score            = -129;

        expected_score_signed = 8'sd0;
        score_errors          = 0;


        // --------------------------------------------------------
        // STEP 2: LOAD INPUT AND REFERENCE OUTPUT FILES
        // --------------------------------------------------------

        $display("STEP 1: Loading test data");

        $readmemh(INPUT_FILE, input_pixels);

        $readmemh(EXPECTED_OUTPUTS_FILE, expected_outputs);

        $display("PASS: Loaded 784 input pixels.");
        $display("PASS: Loaded 32 expected output scores.");
        $display("");


        // --------------------------------------------------------
        // STEP 3: CALCULATE EXPECTED CLASS
        // --------------------------------------------------------

        // The expected output file stores hexadecimal values.
        // The TPU uses signed INT8 output scores.
        //
        // Therefore, interpret the lowest 8 bits of each
        // reference score as a signed 8-bit number.
        //
        // Example:
        //   8'hF9 = 249 when unsigned
        //   8'hF9 = -7  when signed

        expected_class_index = 0;
        max_score = -129;

        for (i = 0; i < NUM_CLASSES; i = i + 1) begin

            expected_score_signed = $signed(expected_outputs[i][7:0]);

            if (expected_score_signed > max_score) begin
                max_score = expected_score_signed;
                expected_class_index = i;
            end

        end

        $display("Reference model predicted class: %0d",
                 expected_class_index);

        $display("Reference maximum signed score: %0d", max_score);
        $display("");


        // --------------------------------------------------------
        // STEP 4: RESET THE COMPLETE SYSTEM
        // --------------------------------------------------------

        repeat (20) @(posedge clk);

        @(negedge clk);
        reset = 1'b0;

        repeat (10) @(posedge clk);

        $display("STEP 2: System reset completed.");
        $display("");


        // --------------------------------------------------------
        // STEP 5: SEND PACKET HEADER
        // --------------------------------------------------------

        $display("STEP 3: Sending packet header 0xAA");

        send_uart_byte(PACKET_HEADER);

        $display("PASS: Packet header transmitted.");
        $display("");


        // --------------------------------------------------------
        // STEP 6: SEND ALL 784 IMAGE PIXELS
        // --------------------------------------------------------

        $display("STEP 4: Sending 784 image pixels over UART");
        $display("This may take a little while...");

        for (i = 0; i < NUM_PIXELS; i = i + 1) begin

            // Send the current pixel as one UART byte.
            send_uart_byte(input_pixels[i]);

        end

        $display("PASS: All 784 image pixels transmitted.");
        $display("");


        // --------------------------------------------------------
        // STEP 7: WAIT FOR THE FPGA TO RETURN ITS PREDICTION
        // --------------------------------------------------------

        $display("STEP 5: Waiting for actual TPU inference...");
        $display("");

        // Wait for the computer-side UART receiver to capture
        // the predicted class returned by the FPGA.
        //
        // The watchdog below prevents an infinite simulation.
        fork

            begin
                wait (received_result_count == 1);
            end

            begin
                #50_000_000;
                $display("ERROR: Timed out waiting for prediction.");
                $fatal(1, "UART-to-TPU system timeout.");
            end

        join_any

        disable fork;


        // Wait for the controller's packet completion pulse too.
        // This is an independent condition from receiving the UART
        // byte, so the monitor has time to count the pulse.
        fork

            begin
                wait (packet_done_count == 1);
            end

            begin
                #1_000_000;
                $display("WARNING: packet_done was not observed.");
            end

        join_any

        disable fork;


        // Give the controller time to finish its status updates.
        repeat (10) @(posedge clk);

        $display("");
        $display("DEBUG: SYSTEM STATUS");
        $display("packet_done_count: %0d", packet_done_count);
        $display("packet_done signal: %b", packet_done);
        $display("controller_busy: %b", controller_busy);
        $display("");


        // --------------------------------------------------------
        // STEP 8: CHECK THE TPU INPUT MEMORY
        // --------------------------------------------------------

        $display("STEP 6: Checking TPU input memory");

        input_errors = 0;

        // Compare every pixel stored inside the actual TPU
        // against the original image loaded by the testbench.
        for (i = 0; i < NUM_PIXELS; i = i + 1) begin

            if (dut.tpu.input_memory[i] !== input_pixels[i]) begin

                input_errors = input_errors + 1;

                // Print only the first 10 mismatches to keep
                // the simulation output readable.
                if (input_errors <= 10) begin
                    $display(
                        "PIXEL MISMATCH at address %0d: expected %h, received %h",
                        i,
                        input_pixels[i],
                        dut.tpu.input_memory[i]
                    );
                end

            end

        end

        $display("Total input pixel mismatches: %0d", input_errors);

        if (input_errors == 0) begin
            $display("PASS: All 784 TPU input pixels match.");
        end
        else begin
            $display("FAIL: TPU input memory does not match the image.");
        end

        $display("");


        // --------------------------------------------------------
        // STEP 9: COMPARE ALL 32 OUTPUT SCORES
        // --------------------------------------------------------

        $display("STEP 7: Comparing all 32 TPU output scores");
        $display("");

        score_errors = 0;

        $display("CLASS | EXPECTED SIGNED | ACTUAL SIGNED | ACTUAL HEX | RESULT");
        $display("-------------------------------------------------------------");

        for (i = 0; i < NUM_CLASSES; i = i + 1) begin

            // Interpret the reference score as signed INT8.
            expected_score_signed = $signed(expected_outputs[i][7:0]);

            if (expected_score_signed !== dut.tpu.output_scores[i]) begin

                score_errors = score_errors + 1;

                $display(
                    "%5d | %15d | %13d | 0x%02h | FAIL",
                    i,
                    expected_score_signed,
                    $signed(dut.tpu.output_scores[i]),
                    dut.tpu.output_scores[i]
                );

            end
            else begin

                $display(
                    "%5d | %15d | %13d | 0x%02h | PASS",
                    i,
                    expected_score_signed,
                    $signed(dut.tpu.output_scores[i]),
                    dut.tpu.output_scores[i]
                );

            end

        end

        $display("-------------------------------------------------------------");
        $display("Total score mismatches: %0d", score_errors);
        $display("");

        if (score_errors == 0) begin
            $display("PASS: All 32 TPU output scores match the reference.");
        end
        else begin
            $display("FAIL: TPU output scores do not match the reference.");
        end

        $display("");


        // --------------------------------------------------------
        // STEP 10: CHECK THE RETURNED PREDICTION
        // --------------------------------------------------------

        $display("STEP 8: Checking returned prediction");

        $display("Expected class: %0d", expected_class_index);
        $display("Returned class: %0d", computer_rx_data);
        $display("TPU predicted class: %0d", predicted_class);
        $display("");

        if (input_errors != 0) begin
            $fatal(1, "TPU input memory mismatch.");
        end

        if (computer_rx_data[7:5] !== 3'b000) begin
            $fatal(1, "Invalid result byte.");
        end

        if (score_errors != 0) begin
            $fatal(1, "TPU output score mismatch. See score table above.");
        end

        if (computer_rx_data[4:0] !== expected_class_index[4:0]) begin
            $fatal(1, "Returned class does not match reference.");
        end

        if (predicted_class !== expected_class_index[4:0]) begin
            $fatal(1, "Incorrect TPU predicted_class.");
        end

        $display("PASS: Returned class matches reference.");
        $display("");


        // --------------------------------------------------------
        // STEP 11: CHECK PACKET AND UART STATUS
        // --------------------------------------------------------

        $display("STEP 9: Checking system status");

        if (packet_done_count != 1) begin
            $display("FAIL: Expected 1 packet_done pulse, got %0d",
                     packet_done_count);
            $fatal(1, "Incorrect packet completion count.");
        end

        $display("PASS: Exactly one packet completed.");

        if (packet_error_count != 0) begin
            $display("FAIL: Packet errors detected: %0d",
                     packet_error_count);
            $fatal(1, "Packet error detected.");
        end

        $display("PASS: No packet errors detected.");

        if (framing_error_count != 0) begin
            $display("FAIL: UART framing errors detected: %0d",
                     framing_error_count);
            $fatal(1, "UART framing error detected.");
        end

        $display("PASS: No UART framing errors detected.");

        if (controller_busy !== 1'b0) begin
            $display("FAIL: Controller did not return to IDLE.");
            $fatal(1, "Controller is still busy.");
        end

        $display("PASS: Controller returned to IDLE.");
        $display("");


        // --------------------------------------------------------
        // STEP 12: FINAL TEST RESULT
        // --------------------------------------------------------

        $display("================================================");
        $display("          COMPLETE SYSTEM TEST SUMMARY");
        $display("================================================");

        $display("Input pixels transmitted: 784");
        $display("UART result bytes received: %0d",
                 received_result_count);

        $display("Expected class: %0d", expected_class_index);
        $display("Actual class:   %0d", computer_rx_data[4:0]);

        $display("Output score mismatches: %0d", score_errors);

        $display("Packet completions: %0d", packet_done_count);
        $display("Packet errors:      %0d", packet_error_count);
        $display("UART framing errors: %0d", framing_error_count);

        // Print the measured TPU inference latency.
        $display("");

        if (tpu_inference_measured) begin

            $display("TPU INFERENCE PERFORMANCE:");
            $display("Clock frequency: 100 MHz");
            $display("Clock cycles:    %0d", tpu_inference_cycles);

            $display(
                "Inference time:  %0.6f ms",
                tpu_inference_time_ms
            );

        end
        else begin

            $display("WARNING: TPU inference timing was not captured.");

        end

        $display("");

        $display("SUCCESS: COMPLETE UART-TO-TPU SYSTEM VERIFIED!");
        $display("All 784 pixels were transferred correctly.");
        $display("All 32 TPU output scores match the reference.");
        $display("The FPGA successfully returned its prediction over UART.");

        $display("================================================");

        $finish;

    end

endmodule
